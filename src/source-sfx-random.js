const MULTIPLIER=f32(2.3283064365386963e-10);

// Returns the post-draw seed as well as the sampled value. Equal endpoints
// intentionally still advance the state, matching the source call contract.
export function sourceSfxRandom({seed,min,max}){
  seed>>>=0;
  const byte0=seed&0xff;
  const byte1=(seed>>>8)&0xff;
  const byte2=(seed>>>16)&0xff;
  const byte3=(seed>>>24)&0xff;
  const mixed=((SOURCE_SFX_RANDOM_TABLE[byte1]<<16)+(SOURCE_SFX_RANDOM_TABLE[byte0]<<24)+
    (SOURCE_SFX_RANDOM_TABLE[byte2]<<8)+SOURCE_SFX_RANDOM_TABLE[byte3])>>>0;
  const next=(seed^mixed)>>>0;
  min=f32(min);max=f32(max);
  return {seed:next,value:f32(f32(f32(max-min)*f32(f32(next)*MULTIPLIER))+min)};
}
